  test('ban chủ nhiệm xử lý hết tồn đọng của người bị đưa ra', async ({ page }, testInfo) => {
    await loginAs(page, 'anh.nguyen@demo.test')
    await page.goto('/clubs/c-guitar/members')
    await page.getByRole('button', { name: /Bùi Đức Long/ }).click()
    const sheet = page.getByRole('dialog', { name: 'Bùi Đức Long' })
    await sheet.getByRole('button', { name: 'Đưa ra khỏi CLB' }).click()
    const remove = page.getByRole('dialog', { name: 'Đưa ra khỏi CLB' })
    await remove.getByRole('textbox', { name: 'Lý do' }).fill('Vi phạm nội quy nhiều lần, đã nhắc nhở.')
    await remove.getByRole('button', { name: 'Đưa ra khỏi CLB' }).click()
    await expect(page.getByText('Đã đưa Bùi Đức Long ra khỏi CLB. 4 mục tồn đọng chờ gán lại.')).toBeVisible()
    await sheet.getByRole('button', { name: 'Xử lý tồn đọng' }).click()
    await page.mouse.move(1, 1)
    await page.waitForURL(/tab=backlog&former=u-long/)

    await expect(page.getByRole('tab', { name: /Tồn đọng/ })).toContainText('4')
    const group = page.getByRole('list', { name: 'Tồn đọng của Bùi Đức Long' })
    await expect(group.getByRole('listitem')).toHaveCount(4)
    await snap(page, testInfo, 'backlogPanel')

    const settle = (toast: string) => settleToast(page, toast)
    const choose = async (button: string, title: string, person: RegExp, submit: string, toast: string) => {
      await group.getByRole('button', { name: button }).click()
      const resolve = page.getByRole('dialog', { name: title })
      await resolve.getByRole('radio', { name: person }).check()
      await resolve.getByRole('button', { name: submit, exact: true }).click()
      await settle(toast)
      await expect(group.getByRole('button', { name: button })).toHaveCount(0)
    }
    await group.getByRole('button', { name: 'Chỉ định người thay: Trưởng ban Hậu cần' }).click()
    const appoint = page.getByRole('dialog', { name: 'Chỉ định người thay' })
    // Trưởng ban phải là thành viên Chính thức của ban (BR-ORG-01): Trâm còn Thử việc nên không có trong danh sách.
    await expect(appoint.getByRole('radio', { name: /Ngô Bảo Trâm/ })).toHaveCount(0)
    await appoint.getByRole('radio', { name: /Phan Anh Khoa/ }).check()
    await snap(page, testInfo, 'backlogResolveSheet', { fullPage: false })
    await appoint.getByRole('button', { name: 'Chỉ định', exact: true }).click()
    await settle('Đã chỉ định Phan Anh Khoa.')

    await choose('Giao lại: Chuẩn bị âm thanh phòng tập', 'Giao lại việc', /Ngô Bảo Trâm/, 'Giao lại', 'Đã giao lại việc cho Ngô Bảo Trâm.')
    await choose('Đổi người nghiệm thu: Mượn loa từ CLB bạn', 'Đổi người nghiệm thu', /Võ Ngọc Mai/, 'Đổi người nghiệm thu', 'Đã đổi người nghiệm thu thành Võ Ngọc Mai.')

    await group.getByRole('button', { name: 'Không cần thay: Trưởng tiểu ban Hậu cần' }).click()
    const dismiss = page.getByRole('dialog', { name: 'Không cần người thay' })
    await dismiss.getByRole('textbox', { name: 'Lý do' }).fill('Tiểu ban gộp vào Truyền thông.')
    await dismiss.getByRole('button', { name: 'Ghi nhận' }).click()
    await expect(page.getByText('Đã ghi nhận chức vụ không cần người thay.')).toBeVisible()

    await expect(page.getByText('Không còn tồn đọng chờ xử lý')).toBeVisible()
    await expect(page.getByRole('tab', { name: /Tồn đọng/ })).toContainText('0')
    await page.getByRole('button', { name: 'Đã xử lý', exact: true }).click()
    await expect(group.getByRole('listitem')).toHaveCount(4)
    await expect(group.getByText(/^Đã giao lại cho Ngô Bảo Trâm · /)).toBeVisible()
    await expect(group.getByText(/^Không cần thay: Tiểu ban gộp vào Truyền thông\. · /)).toBeVisible()
    await snap(page, testInfo, 'backlogResolved')
  })

