    await expect(sheet.getByText('Trưởng nhóm nội dung · Ban Truyền thông · Chính thức')).toBeVisible()
    // Ghi chú hiện ở mục ghi chú và ở dòng lịch sử chỉnh sửa.
    await expect(sheet.getByText('Đang kèm hai bạn thử việc viết bài.')).toHaveCount(2)
