    await form.getByRole('textbox', { name: 'Chức danh hiển thị' }).fill('Trưởng nhóm nội dung')
    await form.getByRole('textbox', { name: 'Ghi chú nội bộ' }).fill('Đang kèm hai bạn thử việc viết bài.')
    await form.getByRole('textbox', { name: 'Ngày gia nhập' }).fill('01/01/2010')
    await form.getByRole('button', { name: 'Lưu thay đổi' }).click()
    await expect(form.getByText('Ngày gia nhập không được trước ngày thành lập CLB (15/09/2016).')).toBeVisible()
