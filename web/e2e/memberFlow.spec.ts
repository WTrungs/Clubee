    await snap(page, testInfo, 'memberInfoForm', { fullPage: false })
    await form.getByRole('button', { name: 'Lưu thay đổi' }).click()
    await expect(page.getByText('Đã lưu thông tin của Hoàng Thảo Vy.')).toBeVisible()
