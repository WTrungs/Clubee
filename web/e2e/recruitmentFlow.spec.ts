import { expect, test } from '@playwright/test'
import { expectNoHorizontalScroll, loginAs, openNavLink, settleToast, snap } from './helpers.ts'

// Năm sau để đợt mới luôn ở Sắp mở.
const year = new Date().getFullYear() + 1

test.describe('Tuyển thành viên', () => {
  test('ban chủ nhiệm mở đợt tuyển với chỉ tiêu, vòng, câu hỏi và giám khảo', async ({ page }, testInfo) => {
    await loginAs(page, 'anh.nguyen@demo.test')
    await page.goto('/clubs/c-guitar')
    await openNavLink(page, 'Tuyển thành viên')
    const list = page.getByRole('list', { name: 'Đợt tuyển' })
    await expect(list.getByRole('link', { name: /Tuyển thành viên học kỳ 1 năm học 2026–2027/ })).toContainText('Đang nhận đơn')
    await expectNoHorizontalScroll(page)
    await snap(page, testInfo, 'recruitmentList')

    await page.getByRole('button', { name: 'Mở đợt tuyển' }).click()
    const sheet = page.getByRole('dialog', { name: 'Mở đợt tuyển' })
    await sheet.getByRole('textbox', { name: 'Tên đợt tuyển' }).fill('Tuyển thành viên học kỳ 2')
    await sheet.getByRole('textbox', { name: 'Mở', exact: true }).fill(`01/02/${year}`)
    await sheet.getByRole('textbox', { name: 'Đóng', exact: true }).fill(`15/02/${year}`)
    await sheet.getByRole('combobox', { name: 'Ban 1' }).selectOption({ label: 'Truyền thông' })
    await sheet.getByRole('textbox', { name: 'Chỉ tiêu' }).fill('0')
    await sheet.getByRole('button', { name: 'Mở đợt tuyển' }).click()
    await expect(sheet.getByText('Từ 1 đến 500.')).toBeVisible()
    await sheet.getByRole('textbox', { name: 'Chỉ tiêu' }).fill('4')
    await sheet.getByRole('button', { name: 'Thêm vòng' }).click()
    // Tên vòng dài để kiểm chip vòng không làm trang tràn ngang ở 360 px.
    await sheet.getByRole('textbox', { name: 'Vòng 2' }).fill('Phỏng vấn trực tiếp cùng trưởng ban và một thành viên ban chủ nhiệm')
    await sheet.getByRole('button', { name: 'Thêm câu hỏi' }).click()
    await sheet.getByRole('textbox', { name: 'Câu 1' }).fill('Vì sao bạn muốn vào ban Truyền thông?')
    await sheet.getByRole('list', { name: 'Chọn giám khảo' }).getByRole('checkbox', { name: /Đặng Khánh Linh/ }).check()
    await expectNoHorizontalScroll(page)
    await snap(page, testInfo, 'recruitmentForm')
    await sheet.getByRole('button', { name: 'Mở đợt tuyển' }).click()
    await settleToast(page, 'Đã mở đợt tuyển Tuyển thành viên học kỳ 2.')

    await expect(page.getByRole('heading', { name: 'Tuyển thành viên học kỳ 2' })).toBeVisible()
    await expect(page.getByText('Sắp mở')).toBeVisible()
    await expect(page.getByRole('list', { name: 'Các vòng' })).toContainText('Phỏng vấn')
    await expect(page.getByRole('list', { name: 'Giám khảo' })).toContainText('Đặng Khánh Linh')
    await expectNoHorizontalScroll(page)
    await snap(page, testInfo, 'recruitmentDetail')
    await page.getByRole('tab', { name: 'Lọc theo vòng' }).click()
    await expect(page.getByRole('group', { name: 'Chọn vòng' }).getByRole('button')).toHaveCount(2)
    await expectNoHorizontalScroll(page)
  })

  test('đợt đang nhận đơn khóa vòng và câu hỏi, vẫn sửa được tên', async ({ page }) => {
    await loginAs(page, 'anh.nguyen@demo.test')
    await page.goto('/clubs/c-guitar/recruitments/rec-guitar-k1')
    await page.getByRole('button', { name: 'Sửa đợt tuyển' }).click()
    const sheet = page.getByRole('dialog', { name: /^Sửa / })
    await expect(sheet.getByRole('textbox', { name: 'Vòng 1' })).toBeDisabled()
    await expect(sheet.getByRole('button', { name: 'Thêm vòng' })).toHaveCount(0)
    await sheet.getByRole('textbox', { name: 'Tên đợt tuyển' }).fill('Tuyển thành viên K1')
    await sheet.getByRole('button', { name: 'Lưu thay đổi' }).click()
    await settleToast(page, 'Đã lưu Tuyển thành viên K1.')
    await expect(page.getByRole('heading', { name: 'Tuyển thành viên K1' })).toBeVisible()
  })

  test('người ngoài CLB nộp đơn, xem ở Đơn của tôi rồi rút; ban chủ nhiệm xem đơn', async ({ page }, testInfo) => {
    await loginAs(page, 'tam.duong@demo.test')
    await openNavLink(page, 'Tìm CLB')
    await page.getByRole('tab', { name: 'Đợt tuyển đang mở' }).click()
    await page.getByRole('list', { name: 'Đợt tuyển đang mở' }).getByRole('link', { name: /Tuyển thành viên học kỳ 1/ }).click()
    await expect(page.getByRole('heading', { name: 'Tuyển thành viên học kỳ 1 năm học 2026–2027' })).toBeVisible()

    await page.getByRole('button', { name: 'Nộp đơn' }).click()
    await expect(page.getByText('Chọn nguyện vọng 1.')).toBeVisible()
    await page.getByRole('combobox', { name: 'Nguyện vọng 1' }).selectOption({ label: 'Chuyên môn' })
    await page.getByRole('combobox', { name: 'Nguyện vọng 2' }).selectOption({ label: 'Chuyên môn' })
    await expect(page.getByRole('combobox', { name: 'Nguyện vọng 2' })).toHaveValue('d-music')
    await page.getByRole('button', { name: 'Nộp đơn' }).click()
    await expect(page.getByText('Ban này đã chọn ở nguyện vọng trước.')).toBeVisible()
    await page.getByRole('combobox', { name: 'Nguyện vọng 2' }).selectOption({ label: 'Truyền thông' })
    await page.getByRole('textbox', { name: 'Vì sao bạn muốn tham gia CLB Guitar?' }).fill('Mình thích đàn và muốn chơi cùng mọi người.')
    await page.getByRole('textbox', { name: 'Bạn đã chơi nhạc cụ nào chưa? Kể ngắn gọn.' }).fill('Chưa chơi nhạc cụ nào.')
    await page.getByRole('textbox', { name: 'MSSV' }).fill('23520456')
    await expectNoHorizontalScroll(page)
    await snap(page, testInfo, 'recruitmentApply')
    await page.getByRole('button', { name: 'Nộp đơn' }).click()
    await settleToast(page, 'Đã nộp đơn. Theo dõi kết quả ở đây hoặc ở tab Đơn của tôi.')
    const mine = page.getByRole('region', { name: 'Đơn của bạn' })
    await expect(mine.getByText('Đã nộp')).toBeVisible()
    await expect(mine).toContainText('1. Chuyên môn · 2. Truyền thông')

    await openNavLink(page, 'Tìm CLB')
    await page.getByRole('tab', { name: 'Đơn của tôi' }).click()
    const list = page.getByRole('list', { name: 'Đơn của tôi' })
    await expect(list.getByRole('listitem')).toHaveCount(1)
    await expectNoHorizontalScroll(page)
    await snap(page, testInfo, 'recruitmentMyApplications')
    await list.getByRole('button', { name: /^Rút đơn/ }).click()
    await page.getByRole('dialog', { name: 'Rút đơn ứng tuyển' }).getByRole('button', { name: 'Rút đơn' }).click()
    await settleToast(page, 'Đã rút đơn ứng tuyển Tuyển thành viên học kỳ 1 năm học 2026–2027.')
    await expect(list.getByText('Đã rút')).toBeVisible()

    // Đăng nhập lại trong app để dữ liệu mock vừa ghi còn nguyên; sau đăng nhập app quay về trang đang xem chứ không về /clubs.
    await page.getByRole('button', { name: 'Tài khoản: Dương Thanh Tâm' }).click()
    await page.getByRole('menuitem', { name: 'Đăng xuất' }).click()
    await page.waitForURL('**/login**')
    await page.getByRole('textbox', { name: 'Email' }).fill('anh.nguyen@demo.test')
    await page.getByRole('textbox', { name: 'Mật khẩu', exact: true }).fill(crypto.randomUUID())
    await page.getByRole('button', { name: 'Đăng nhập' }).click()
    await page.waitForURL((url) => !url.pathname.startsWith('/login'))
    await openNavLink(page, 'CLB của tôi')
    await page.getByRole('button', { name: /^CLB Guitar Sinh viên .*Vào CLB$/ }).click()
    await page.waitForURL('**/clubs/c-guitar')
    await openNavLink(page, 'Tuyển thành viên')
    await page.getByRole('list', { name: 'Đợt tuyển' }).getByRole('link').first().click()
    await page.getByRole('tab', { name: /Đơn ứng tuyển/ }).click()
    const applications = page.getByRole('list', { name: 'Đơn ứng tuyển' })
    await expect(applications.getByRole('listitem')).toHaveCount(3)
    await applications.getByRole('button', { name: /Châu/ }).click()
    await expect(page.getByRole('dialog').getByText('Vì sao bạn muốn tham gia CLB Guitar?')).toBeVisible()
    await expectNoHorizontalScroll(page)
    await snap(page, testInfo, 'recruitmentApplications')
  })

  test('ban chủ nhiệm lọc đơn theo vòng: Đạt kèm điểm, Loại kèm nhận xét', async ({ page }, testInfo) => {
    await loginAs(page, 'anh.nguyen@demo.test')
    await page.goto('/clubs/c-guitar/recruitments/rec-guitar-k1?tab=rounds')
    const list = page.getByRole('list', { name: 'Đơn theo vòng' })
    await expect(list.getByRole('listitem')).toHaveCount(1)
    await list.getByRole('button', { name: 'Đạt: Hồ Tấn Đạt' }).click()
    const dialog = page.getByRole('dialog', { name: 'Xét vòng: Hồ Tấn Đạt' })
    await dialog.getByRole('textbox', { name: /^Điểm/ }).fill('101')
    await dialog.getByRole('button', { name: 'Ghi Đạt' }).click()
    await expect(dialog.getByText('Nhập điểm nguyên từ 0 đến 100.')).toBeVisible()
    await dialog.getByRole('textbox', { name: /^Điểm/ }).fill('75')
    await expectNoHorizontalScroll(page)
    await snap(page, testInfo, 'recruitmentRoundDialog', { fullPage: false })
    await dialog.getByRole('button', { name: 'Ghi Đạt' }).click()
    await settleToast(page, 'Hồ Tấn Đạt đạt vòng này.')
    await expect(page.getByText('Không có đơn nào ở bộ lọc này')).toBeVisible()

    await page.getByRole('group', { name: 'Chọn vòng' }).getByRole('button', { name: /Vòng 2: Phỏng vấn/ }).click()
    await expect(list.getByRole('listitem')).toHaveCount(2)
    await list.getByRole('button', { name: 'Loại: Châu Minh Tú' }).click()
    const tuDialog = page.getByRole('dialog', { name: 'Xét vòng: Châu Minh Tú' })
    await tuDialog.getByRole('textbox', { name: 'Nhận xét' }).fill('Chưa sắp xếp được lịch tập cố định.')
    await tuDialog.getByRole('button', { name: 'Ghi Loại' }).click()
    await settleToast(page, 'Đã loại Châu Minh Tú ở vòng này.')
    await page.getByRole('group', { name: 'Lọc theo kết quả vòng' }).getByRole('button', { name: /^Loại/ }).click()
    await expect(list.getByRole('listitem').filter({ hasText: 'Châu Minh Tú' })).toContainText('Chưa sắp xếp được lịch tập cố định.')
    await expect(list.getByRole('button', { name: 'Sửa kết quả: Châu Minh Tú' })).toBeVisible()
    await expectNoHorizontalScroll(page)
    await snap(page, testInfo, 'recruitmentRounds')
  })

  test('thành viên CLB thấy lý do không nộp đơn được', async ({ page }) => {
    await loginAs(page, 'ha.le@demo.test')
    await page.goto('/recruitments/rec-guitar-k1')
    await expect(page.getByText('Bạn đang là thành viên hoặc đang chờ duyệt vào CLB này nên không nộp đơn được.')).toBeVisible()
    await expect(page.getByRole('button', { name: 'Nộp đơn' })).toHaveCount(0)
  })

  test('thành viên thường không thấy mục Tuyển thành viên', async ({ page }) => {
    await loginAs(page, 'ha.le@demo.test')
    await page.goto('/clubs/c-guitar')
    if ((page.viewportSize()?.width ?? 1440) < 1024) await page.getByRole('button', { name: 'Mở menu' }).click()
    const nav = page.getByRole('navigation', { name: 'Điều hướng chính' }).filter({ visible: true }).first()
    await expect(nav.getByRole('link', { name: 'Tài chính', exact: true })).toBeVisible()
    await expect(nav.getByRole('link', { name: 'Tuyển thành viên', exact: true })).toHaveCount(0)
  })
})
