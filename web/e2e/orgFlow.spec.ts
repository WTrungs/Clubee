import { expect, test, type Page } from '@playwright/test'
import { expectNoHorizontalScroll, loginAs, openNavLink, snap, useDarkTheme } from './helpers.ts'

// Tên nút của thẻ ban bắt đầu bằng "Ban <tên> <số> người"; không dùng \b vì không khớp sau chữ có dấu.
const departmentCard = (page: Page, name: string) => page.getByRole('button', { name: new RegExp(`^Ban ${name} \\d+ người`) })

test.describe('Cơ cấu', () => {
  test('ban chủ nhiệm khai báo, sửa và đóng ban rỗng', async ({ page }, testInfo) => {
    await loginAs(page, 'anh.nguyen@demo.test')
    await page.goto('/clubs/c-guitar/structure')
    await expect(page.getByRole('heading', { name: 'Cơ cấu', exact: true })).toBeVisible()
    await snap(page, testInfo, 'orgStructure')

    await page.getByRole('button', { name: 'Thêm ban' }).click()
    const create = page.getByRole('dialog', { name: 'Thêm ban chuyên môn' })
    await create.getByRole('textbox', { name: 'Tên ban' }).fill('Truyền thông')
    await create.getByRole('button', { name: 'Thêm ban' }).click()
    await expect(create.getByText('CLB đã có ban đang hoạt động trùng tên.')).toBeVisible()
    await create.getByRole('textbox', { name: 'Tên ban' }).fill('Hậu kỳ')
    await create.getByRole('textbox', { name: 'Mô tả' }).fill('Thu âm và dựng video các buổi diễn.')
    await create.getByRole('button', { name: 'Thêm ban' }).click()
    await expect(page.getByText('Đã khai báo ban Hậu kỳ.')).toBeVisible()

    await departmentCard(page, 'Hậu kỳ').click()
    await page.getByRole('button', { name: 'Sửa', exact: true }).click()
    const edit = page.getByRole('dialog', { name: 'Sửa ban Hậu kỳ' })
    await edit.getByRole('textbox', { name: 'Tên ban' }).fill('Hậu kỳ âm thanh')
    await edit.getByRole('button', { name: 'Lưu thay đổi' }).click()
    await expect(page.getByText('Đã lưu thông tin ban Hậu kỳ âm thanh.')).toBeVisible()

    await page.getByRole('button', { name: 'Đóng ban' }).click()
    const close = page.getByRole('dialog', { name: 'Đóng ban' })
    await close.getByRole('textbox', { name: 'Lý do' }).fill('Gộp vào ban Truyền thông cho gọn.')
    await close.getByRole('button', { name: 'Đóng ban' }).click()
    await expect(page.getByText('Đã đóng ban Hậu kỳ âm thanh. Ban vẫn tra cứu được ở mục Đã đóng.')).toBeVisible()
    await page.keyboard.press('Escape')
    await page.getByRole('button', { name: 'Đã đóng', exact: true }).click()
    await expect(departmentCard(page, 'Hậu kỳ âm thanh')).toBeVisible()
    await expect(departmentCard(page, 'Nhiếp ảnh')).toBeVisible()
  })

  test('đóng ban còn thành viên bị chặn kèm lý do', async ({ page }) => {
    await loginAs(page, 'anh.nguyen@demo.test')
    await page.goto('/clubs/c-guitar/structure')
    await departmentCard(page, 'Thiết kế').click()
    await page.getByRole('button', { name: 'Đóng ban' }).click()
    const close = page.getByRole('dialog', { name: 'Đóng ban' })
    await close.getByRole('textbox', { name: 'Lý do' }).fill('Thử đóng ban còn người.')
    await close.getByRole('button', { name: 'Đóng ban' }).click()
    await expect(page.getByText(/Ban Thiết kế còn 1 thành viên/)).toBeVisible()
  })

  test('chuyển trưởng ban bị chặn; thu hồi rồi chuyển cả ban và đóng ban', async ({ page }, testInfo) => {
    await loginAs(page, 'anh.nguyen@demo.test')
    await page.goto('/clubs/c-guitar/structure')
    await departmentCard(page, 'Đối ngoại').click()
    await page.getByRole('button', { name: 'Chuyển thành viên' }).click()
    const move = page.getByRole('dialog', { name: 'Chuyển thành viên Ban Đối ngoại' })
    await move.getByRole('combobox', { name: 'Chuyển sang ban' }).selectOption({ label: 'Chuyên môn' })
    await move.getByRole('checkbox', { name: 'Chọn tất cả (2)' }).check()
    await snap(page, testInfo, 'transferMembers', { fullPage: false })
    await move.getByRole('button', { name: 'Chuyển 2 người' }).click()
    await expect(move.getByText(/Tạ Hồng Sơn \(Trưởng ban Đối ngoại\)/)).toBeVisible()
    await move.getByRole('button', { name: 'Hủy bỏ' }).click()

    await page.getByRole('button', { name: 'Thu hồi Trưởng ban Đối ngoại của Tạ Hồng Sơn' }).click()
    const revoke = page.getByRole('dialog', { name: 'Thu hồi chức vụ' })
    await revoke.getByRole('textbox', { name: 'Lý do' }).fill('Gộp ban Đối ngoại vào ban Chuyên môn.')
    await revoke.getByRole('button', { name: 'Thu hồi' }).click()
    await expect(page.getByText('Đã thu hồi chức vụ Trưởng ban Đối ngoại của Tạ Hồng Sơn.')).toBeVisible()

    await page.getByRole('button', { name: 'Chuyển thành viên' }).click()
    await move.getByRole('combobox', { name: 'Chuyển sang ban' }).selectOption({ label: 'Chuyên môn' })
    await move.getByRole('checkbox', { name: 'Chọn tất cả (2)' }).check()
    await move.getByRole('button', { name: 'Chuyển 2 người' }).click()
    await expect(page.getByText('Đã chuyển 2 người sang Ban Chuyên môn.')).toBeVisible()
    await expect(move).toBeHidden()
    await expect(page.getByText('Ban chưa có thành viên.')).toBeVisible()
    await expect(page.getByRole('button', { name: 'Chuyển thành viên' })).toHaveCount(0)

    await page.getByRole('button', { name: 'Đóng ban' }).click()
    const close = page.getByRole('dialog', { name: 'Đóng ban' })
    await close.getByRole('textbox', { name: 'Lý do' }).fill('Gộp vào ban Chuyên môn.')
    await close.getByRole('button', { name: 'Đóng ban' }).click()
    await expect(page.getByText('Đã đóng ban Đối ngoại. Ban vẫn tra cứu được ở mục Đã đóng.')).toBeVisible()
  })

  test('gán Trưởng ban Thiết kế rồi thu hồi Trưởng ban Truyền thông có lý do', async ({ page }, testInfo) => {
    await loginAs(page, 'anh.nguyen@demo.test')
    await page.goto('/clubs/c-guitar/structure')
    await departmentCard(page, 'Thiết kế').click()
    await page.getByRole('button', { name: 'Gán trưởng, phó ban' }).click()
    const assign = page.getByRole('dialog', { name: 'Gán chức vụ' })
    await expect(assign.getByRole('combobox', { name: 'Chức vụ', exact: true })).toHaveValue('DEPARTMENT_HEAD')
    await assign.getByRole('combobox', { name: 'Người giữ chức vụ' }).selectOption({ label: 'Lương Trung Hiếu · Ban Thiết kế' })
    await snap(page, testInfo, 'assignPosition')
    await assign.getByRole('button', { name: 'Gán chức vụ' }).click()
    await expect(page.getByText('Đã gán Trưởng ban Thiết kế cho Lương Trung Hiếu.')).toBeVisible()
    await expect(page.getByRole('button', { name: 'Thu hồi Trưởng ban Thiết kế của Lương Trung Hiếu' })).toBeVisible()
    await snap(page, testInfo, 'departmentDetail')
    await page.keyboard.press('Escape')

    await departmentCard(page, 'Truyền thông').click()
    await page.getByRole('button', { name: 'Thu hồi Trưởng ban Truyền thông của Đặng Khánh Linh' }).click()
    const revoke = page.getByRole('dialog', { name: 'Thu hồi chức vụ' })
    await revoke.getByRole('button', { name: 'Thu hồi' }).click()
    await expect(revoke.getByText('Nhập ít nhất 5 ký tự.')).toBeVisible()
    await revoke.getByRole('textbox', { name: 'Lý do' }).fill('Bàn giao để tập trung học kỳ cuối.')
    await revoke.getByRole('button', { name: 'Thu hồi' }).click()
    await expect(page.getByText('Đã thu hồi chức vụ Trưởng ban Truyền thông của Đặng Khánh Linh.')).toBeVisible()
    await expect(page.getByText('Chưa có trưởng ban.')).toBeVisible()
  })

  test('không thu hồi được Chủ nhiệm cuối cùng', async ({ page }) => {
    await loginAs(page, 'anh.nguyen@demo.test')
    await page.goto('/clubs/c-guitar/structure')
    await page.getByRole('button', { name: 'Thu hồi Chủ nhiệm của Nguyễn Minh Anh' }).click()
    const revoke = page.getByRole('dialog', { name: 'Thu hồi chức vụ' })
    await revoke.getByRole('textbox', { name: 'Lý do' }).fill('Thử thu hồi Chủ nhiệm cuối.')
    await revoke.getByRole('button', { name: 'Thu hồi' }).click()
    await expect(revoke.getByText(/CLB phải luôn có ít nhất một Chủ nhiệm/)).toBeVisible()
  })

  test('gán chức vụ từ hồ sơ thành viên', async ({ page }) => {
    await loginAs(page, 'anh.nguyen@demo.test')
    await page.goto('/clubs/c-guitar/members')
    await page.getByRole('button', { name: /Võ Ngọc Mai/ }).click()
    const sheet = page.getByRole('dialog', { name: 'Võ Ngọc Mai' })
    await expect(sheet.getByText('Thủ quỹ')).toBeVisible()
    await sheet.getByRole('button', { name: 'Gán chức vụ' }).click()
    const assign = page.getByRole('dialog', { name: 'Gán chức vụ' })
    await expect(assign.getByRole('textbox', { name: 'Người giữ chức vụ' })).toHaveValue('Võ Ngọc Mai')
    await assign.getByRole('combobox', { name: 'Chức vụ', exact: true }).selectOption({ label: 'Phó ban' })
    await assign.getByRole('combobox', { name: 'Ban', exact: true }).selectOption({ label: 'Hậu cần' })
    await assign.getByRole('button', { name: 'Gán chức vụ' }).click()
    await expect(page.getByText('Đã gán Phó ban Hậu cần cho Võ Ngọc Mai.')).toBeVisible()
    await expect(sheet.getByText('Phó ban Hậu cần')).toBeVisible()
  })

  test('thành viên thường xem cơ cấu, không có nút quản lý', async ({ page }, testInfo) => {
    await loginAs(page, 'ha.le@demo.test')
    await page.goto('/clubs/c-guitar')
    await openNavLink(page, 'Cơ cấu')
    await expect(page.getByRole('region', { name: 'Ban chủ nhiệm' }).getByText('Nguyễn Minh Anh')).toBeVisible()
    await expect(page.getByRole('button', { name: 'Thêm ban' })).toHaveCount(0)
    await departmentCard(page, 'Truyền thông').click()
    await expect(page.getByText('Lê Thu Hà')).toBeVisible()
    await expect(page.getByRole('button', { name: 'Đóng ban' })).toHaveCount(0)
    await snap(page, testInfo, 'orgMemberView')
  })

  test('sơ đồ CLB hiện trưởng ban, số người và badge trạng thái từng ban', async ({ page }, testInfo) => {
    await loginAs(page, 'anh.nguyen@demo.test')
    await page.goto('/clubs/c-guitar/structure')
    await expect(page.getByRole('heading', { name: 'Sơ đồ CLB' })).toBeVisible()
    await expect(departmentCard(page, 'Truyền thông')).toContainText('Quá hạn')
    await expect(departmentCard(page, 'Chuyên môn')).toContainText('Sắp đến hạn')
    await expect(departmentCard(page, 'Thiết kế')).toContainText('Chưa có trưởng ban')
    await expect(departmentCard(page, 'Đối ngoại')).toContainText('Đúng tiến độ')
    await expect(departmentCard(page, 'Đối ngoại')).toContainText('Trưởng ban: Tạ Hồng Sơn')
    await departmentCard(page, 'Đối ngoại').click()
    await expect(page.getByText('Kha Bảo Ngọc')).toBeVisible()
    await snap(page, testInfo, 'orgChart', { fullPage: testInfo.project.name !== 'mobile360' })
  })

  test('ở 1024 px thẻ ban nằm gọn trong cột, không cuộn ngang', async ({ page }) => {
    test.skip(test.info().project.name !== 'desktop1440', 'Chỉ cần đo một lần ở màn rộng')
    await page.setViewportSize({ width: 1024, height: 900 })
    await loginAs(page, 'anh.nguyen@demo.test')
    await page.goto('/clubs/c-guitar/structure')
    await expect(departmentCard(page, 'Truyền thông')).toBeVisible()
    await expectNoHorizontalScroll(page)
    const column = await page.getByRole('region', { name: 'Ban chủ nhiệm' }).boundingBox()
    for (const card of await page.getByRole('button', { name: /^Ban .+ \d+ người/ }).all()) {
      const box = await card.boundingBox()
      expect(box && column && box.x >= column.x - 1 && box.x + box.width <= column.x + column.width + 1, 'thẻ ban tràn ra ngoài cột').toBe(true)
    }
  })

  test('giao diện tối', async ({ page }, testInfo) => {
    await useDarkTheme(page)
    await loginAs(page, 'anh.nguyen@demo.test')
    await page.goto('/clubs/c-guitar/structure?department=d-media')
    // Màn hẹp có thêm tiêu đề ẩn của Sheet nên lấy tiêu đề đầu tiên.
    await expect(page.getByRole('heading', { name: 'Ban Truyền thông' }).first()).toBeVisible()
    await snap(page, testInfo, 'orgStructureDark')
  })

  test('thành viên tra cứu chức vụ hiện tại, lọc sự kiện và xem nhiệm kỳ đã đóng', async ({ page }, testInfo) => {
    await loginAs(page, 'ha.le@demo.test')
    await page.goto('/clubs/c-guitar/structure')
    await page.getByRole('tab', { name: 'Chức vụ' }).click()
    await expect(page).toHaveURL(/tab=positions/)
    await expect(page.getByText(/^\d+ chức vụ$/)).toBeVisible()
    await expect(page.getByText('Nguyễn Minh Anh').first()).toBeVisible()

    await page.getByRole('group', { name: 'Lọc theo phạm vi' }).getByRole('button', { name: 'Sự kiện' }).click()
    await expect(page.getByText('Trần Quốc Bảo').first()).toBeVisible()
    await expect(page.getByText('Võ Ngọc Mai')).toHaveCount(0)
    await snap(page, testInfo, 'positionsLookup')

    // Chờ trang vẽ lại theo bộ lọc mới rồi mới thao tác tiếp, như người dùng thật.
    const all = page.getByRole('group', { name: 'Lọc theo phạm vi' }).getByRole('button', { name: 'Tất cả' })
    await all.click()
    await expect(all).toHaveAttribute('aria-pressed', 'true')
    await page.getByRole('combobox', { name: 'Nhiệm kỳ' }).selectOption({ label: 'Nhiệm kỳ 2025–2026 (đã đóng)' })
    await expect(page.getByText('7 chức vụ')).toBeVisible()
    await expect(page.getByText('Hồ Tấn Đạt').first()).toBeVisible()
    await expect(page.getByText('Truyền thông và Sự kiện').first()).toBeVisible()
    // Thành viên thường không thấy lý do thu hồi (SRS 3.5).
    await expect(page.getByText('Xin thôi chức để tập trung thi cuối kỳ.', { exact: false })).toHaveCount(0)
    await page.getByRole('searchbox', { name: 'Tìm theo tên người, ban hoặc sự kiện' }).fill('hau can')
    await expect(page.getByText('2 chức vụ')).toBeVisible()
    await snap(page, testInfo, 'positionsClosedTerm')
  })
})
