import { expect, test } from '@playwright/test'
import { loginAs, openNavLink, openNotification, settleToast, snap, switchUser, useDarkTheme } from './helpers.ts'

test.describe('Sự kiện', () => {
  test('danh sách và tổng quan CLB', async ({ page }, testInfo) => {
    await loginAs(page, 'anh.nguyen@demo.test')
    await page.goto('/clubs/c-guitar')
    await expect(page.getByText('Việc gần hạn nhất')).toBeVisible()
    await snap(page, testInfo, 'clubDashboard')

    await page.goto('/clubs/c-guitar/events')
    await expect(page.getByRole('heading', { name: 'Sự kiện', exact: true })).toBeVisible()
    await expect(page.getByText('Đêm nhạc Mùa đông')).toBeVisible()
    await snap(page, testInfo, 'eventList')
  })

  test('ban chủ nhiệm duyệt đề xuất, người đề xuất thành Trưởng BTC', async ({ page }, testInfo) => {
    await loginAs(page, 'anh.nguyen@demo.test')
    await page.goto('/clubs/c-guitar/events')
    await page.getByRole('link', { name: /Biểu diễn đường phố gây quỹ/ }).click()
    await expect(page.getByRole('heading', { name: 'Biểu diễn đường phố gây quỹ' })).toBeVisible()
    await snap(page, testInfo, 'eventPending')
    await page.getByRole('button', { name: 'Duyệt', exact: true }).click()
    const dialog = page.getByRole('dialog', { name: 'Duyệt đề xuất' })
    await expect(dialog.getByRole('combobox', { name: 'Trưởng BTC' })).toHaveValue('u-ha')
    await dialog.getByRole('button', { name: 'Duyệt sự kiện' }).click()
    await expect(page.getByText('Đã duyệt sự kiện.')).toBeVisible()
    await expect(page.getByRole('button', { name: 'Mở đăng ký' })).toBeVisible()
  })

  test('từ chối bắt buộc lý do', async ({ page }) => {
    await loginAs(page, 'anh.nguyen@demo.test')
    await page.goto('/clubs/c-guitar/events')
    await page.getByRole('link', { name: /Biểu diễn đường phố gây quỹ/ }).click()
    await page.getByRole('button', { name: 'Từ chối' }).click()
    const dialog = page.getByRole('dialog', { name: 'Từ chối đề xuất' })
    await dialog.getByRole('button', { name: 'Từ chối' }).click()
    await expect(dialog.getByText('Vui lòng nhập ít nhất 5 ký tự.')).toBeVisible()
    await dialog.getByRole('textbox', { name: 'Lý do' }).fill('Thiếu kế hoạch an toàn khi biểu diễn ngoài trời.')
    await dialog.getByRole('button', { name: 'Từ chối' }).click()
    await expect(page.getByText('Đề xuất bị từ chối:')).toBeVisible()
    // Hỏi lại máy chủ qua danh sách (không tải lại trang vì mock nằm trong trình duyệt): ban chủ nhiệm vẫn thấy đề xuất đã từ chối.
    await page.getByRole('link', { name: 'Tất cả sự kiện' }).click()
    await page.getByRole('button', { name: 'Dự thảo' }).click()
    await expect(page.getByRole('link', { name: /Biểu diễn đường phố gây quỹ/ })).toBeVisible()
  })

  test('thành viên đăng ký nhận chỗ cuối cùng', async ({ page }, testInfo) => {
    await loginAs(page, 'ha.le@demo.test')
    await page.goto('/clubs/c-guitar/events/e-winter?tab=registrations')
    await expect(page.getByText('Còn 1 chỗ')).toBeVisible()
    await page.getByRole('button', { name: 'Đăng ký tham dự' }).click()
    await expect(page.getByText('Đăng ký thành công, bạn đã có chỗ.')).toBeVisible()
    await expect(page.getByText('Bạn đã đăng ký')).toBeVisible()
    await snap(page, testInfo, 'eventRegistered')
  })

  test('người giữ chỗ hủy đăng ký, người đầu danh sách chờ được nhận chỗ và có thông báo', async ({ page }, testInfo) => {
    const openWinterRegistrations = async () => {
      await openNavLink(page, 'Sự kiện')
      await page.getByRole('link', { name: /Đêm nhạc Mùa đông/ }).click()
      await page.getByRole('tab', { name: 'Đăng ký' }).click()
    }
    await loginAs(page, 'ha.le@demo.test')
    await page.goto('/clubs/c-guitar/events/e-winter?tab=registrations')
    await page.getByRole('button', { name: 'Đăng ký tham dự' }).click()
    await settleToast(page, 'Đăng ký thành công, bạn đã có chỗ.')

    await switchUser(page, 'Lê Thu Hà', 'bao.tran@demo.test')
    await openWinterRegistrations()
    await page.getByRole('button', { name: 'Vào danh sách chờ' }).click()
    await expect(page.getByRole('region', { name: 'Tình hình đăng ký' }).getByText('Danh sách chờ · #1')).toBeVisible()

    await switchUser(page, 'Trần Quốc Bảo', 'ha.le@demo.test')
    await openWinterRegistrations()
    await expect(page.getByText(/^Hủy được đến \d{2}\/\d{2}\/\d{4} \d{2}:\d{2}\.$/)).toBeVisible()
    await page.getByRole('button', { name: 'Hủy đăng ký' }).click()
    const confirm = page.getByRole('dialog', { name: 'Hủy đăng ký?' })
    await expect(confirm.getByText(/người đầu danh sách chờ được nhận chỗ thay/)).toBeVisible()
    await snap(page, testInfo, 'eventCancelRegistration', { fullPage: false })
    await confirm.getByRole('button', { name: 'Hủy đăng ký' }).click()
    await settleToast(page, 'Đã hủy đăng ký.')
    // Chỗ vừa trống đã được đôn cho người chờ nên đăng ký lại sẽ vào danh sách chờ.
    await expect(page.getByRole('button', { name: 'Vào danh sách chờ' })).toBeVisible()

    await switchUser(page, 'Lê Thu Hà', 'bao.tran@demo.test')
    await openNotification(page, /Bạn đã được nhận chỗ: Đêm nhạc Mùa đông/)
    await page.getByRole('tab', { name: 'Đăng ký' }).click()
    await expect(page.getByText(/^Được đôn từ danh sách chờ lúc /)).toBeVisible()
    // Toast đăng xuất ở đáy màn hẹp che dòng cần chụp.
    await expect(page.getByText('Đã đăng xuất.')).toBeHidden({ timeout: 10_000 })
    await page.getByRole('region', { name: 'Tình hình đăng ký' }).scrollIntoViewIfNeeded()
    await snap(page, testInfo, 'eventPromotedFromWaitlist', { fullPage: false })
  })

  test('Trưởng BTC dời giờ, người giữ chỗ nhận thông báo rồi xác nhận lại', async ({ page }, testInfo) => {
    const inTwoWeeks = new Intl.DateTimeFormat('en-GB', { timeZone: 'Asia/Ho_Chi_Minh', day: '2-digit', month: '2-digit', year: 'numeric' }).format(Date.now() + 14 * 24 * 60 * 60 * 1000)
    await loginAs(page, 'bao.tran@demo.test')
    await page.goto('/clubs/c-guitar/events/e-winter')
    await page.getByRole('button', { name: 'Dời thời gian' }).click()
    const sheet = page.getByRole('dialog', { name: 'Dời thời gian' })
    await expect(sheet.getByText(/^11 người đang giữ chỗ sẽ chuyển sang Chờ xác nhận lại/)).toBeVisible()
    for (const label of ['Bắt đầu mới', 'Kết thúc mới']) await sheet.getByRole('textbox', { name: label, exact: true }).fill(inTwoWeeks)
    await sheet.getByRole('textbox', { name: 'Giờ bắt đầu mới' }).fill('18:00')
    await sheet.getByRole('textbox', { name: 'Giờ kết thúc mới' }).fill('21:00')
    await sheet.getByRole('textbox', { name: 'Lý do' }).fill('Hội trường bận sửa chữa hệ thống điện.')
    await snap(page, testInfo, 'eventReschedule', { fullPage: false })
    await sheet.getByRole('button', { name: 'Dời thời gian' }).click()
    await settleToast(page, 'Đã dời thời gian. 11 người giữ chỗ cần xác nhận lại.')
    const banner = page.getByText(/^Đã dời từ .+ sang 18:00 – 21:00, /)
    await expect(banner).toBeVisible()
    await expect(page.getByText('Đã dời thời gian. 11 người giữ chỗ cần xác nhận lại.')).toBeHidden({ timeout: 10_000 })
    await banner.scrollIntoViewIfNeeded()
    await snap(page, testInfo, 'eventRescheduled', { fullPage: false })

    await switchUser(page, 'Trần Quốc Bảo', 'mai.vo@demo.test')
    await openNotification(page, /Sự kiện dời thời gian: Đêm nhạc Mùa đông/)
    await expect(page.getByText('Lý do: Hội trường bận sửa chữa hệ thống điện.')).toBeVisible()
    await page.getByRole('tab', { name: 'Đăng ký' }).click()
    const seat = page.getByRole('region', { name: 'Tình hình đăng ký' })
    await expect(seat.getByText('Chờ xác nhận lại', { exact: true })).toBeVisible()
    await expect(seat.getByText(/^Sự kiện đã dời giờ\. Xác nhận tham dự trước /)).toBeVisible()
    await expect(page.getByText('Đã đăng xuất.')).toBeHidden({ timeout: 10_000 })
    await seat.scrollIntoViewIfNeeded()
    await snap(page, testInfo, 'eventReconfirm', { fullPage: false })
    await seat.getByRole('button', { name: 'Xác nhận tham dự' }).click()
    await settleToast(page, 'Đã xác nhận tham dự theo giờ mới.')
    await expect(seat.getByText('Nhận chỗ', { exact: true })).toBeVisible()
    await expect(seat.getByRole('button', { name: 'Xác nhận tham dự' })).toHaveCount(0)
  })

  test('Trưởng BTC lập tiểu ban và mời thành viên', async ({ page }, testInfo) => {
    await loginAs(page, 'bao.tran@demo.test')
    await page.goto('/clubs/c-guitar/events/e-winter?tab=staff')
    await expect(page.getByRole('heading', { name: 'Tiểu ban Hậu cần' })).toBeVisible()
    await page.getByRole('button', { name: 'Lập tiểu ban' }).click()
    const create = page.getByRole('dialog', { name: 'Lập tiểu ban' })
    await create.getByRole('textbox', { name: 'Tên tiểu ban' }).fill('Lễ tân')
    await create.getByRole('textbox', { name: 'Chỉ tiêu nhân sự' }).fill('2')
    await create.getByRole('combobox', { name: 'Trưởng tiểu ban' }).selectOption({ label: 'Võ Ngọc Mai · Ban Hậu cần' })
    await create.getByRole('button', { name: 'Lập tiểu ban' }).click()
    await expect(page.getByText('Đã lập tiểu ban Lễ tân.')).toBeVisible()

    const card = page.getByRole('listitem').filter({ has: page.getByRole('heading', { name: 'Tiểu ban Lễ tân' }) })
    await card.getByRole('button', { name: 'Mời' }).click()
    const invite = page.getByRole('dialog', { name: 'Mời vào tiểu ban Lễ tân' })
    await invite.getByRole('searchbox', { name: 'Tìm thành viên' }).fill('thao')
    await invite.getByRole('listitem').filter({ hasText: 'Mai Phương Thảo' }).getByRole('button', { name: 'Thêm' }).click()
    await expect(page.getByText('Đã thêm Mai Phương Thảo vào tiểu ban Lễ tân.')).toBeVisible()
    await page.keyboard.press('Escape')
    await snap(page, testInfo, 'eventStaff')
  })

  test('ban chủ nhiệm tạo sự kiện, được duyệt ngay', async ({ page }, testInfo) => {
    await loginAs(page, 'anh.nguyen@demo.test')
    await page.goto('/clubs/c-guitar/events')
    await page.getByRole('button', { name: 'Tạo sự kiện' }).click()
    const sheet = page.getByRole('dialog', { name: 'Tạo sự kiện' })
    await sheet.getByRole('textbox', { name: 'Tên sự kiện' }).fill('Buổi tập mở cho tân thành viên')
    await sheet.getByRole('textbox', { name: 'Địa điểm' }).fill('Phòng tập B1')
    await sheet.getByRole('textbox', { name: 'Số chỗ' }).fill('20')
    await sheet.getByRole('combobox', { name: 'Trưởng BTC' }).selectOption({ label: 'Lý Tuấn Kiệt · Ban Chuyên môn' })
    await snap(page, testInfo, 'eventForm')
    await sheet.getByRole('button', { name: 'Tạo sự kiện' }).click()
    await expect(page.getByRole('heading', { name: 'Buổi tập mở cho tân thành viên' })).toBeVisible()
    await expect(page.getByRole('button', { name: 'Mở đăng ký' })).toBeVisible()
  })

  test('thành viên thường đề xuất và không thấy danh sách tham dự', async ({ page }, testInfo) => {
    await loginAs(page, 'ha.le@demo.test')
    await page.goto('/clubs/c-guitar/events')
    await expect(page.getByRole('button', { name: 'Đề xuất sự kiện' })).toBeVisible()
    await page.goto('/clubs/c-guitar/events/e-workshop?tab=registrations')
    await expect(page.getByText('Sự kiện hiện không nhận đăng ký.')).toBeVisible()
    await expect(page.getByText('Danh sách tham dự')).toHaveCount(0)
    await snap(page, testInfo, 'eventMemberView')
  })

  test('giao diện tối', async ({ page }, testInfo) => {
    await useDarkTheme(page)
    await loginAs(page, 'bao.tran@demo.test')
    await page.goto('/clubs/c-guitar/events/e-winter')
    await expect(page.getByRole('heading', { name: 'Đêm nhạc Mùa đông' })).toBeVisible()
    await snap(page, testInfo, 'eventDetailDark')
  })
})
